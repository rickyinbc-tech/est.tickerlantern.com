"""Extract a small attributed public-data snapshot; raw StatCan downloads stay in qa/."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import zipfile

parser = argparse.ArgumentParser()
parser.add_argument('--archive', required=True)
parser.add_argument('--output', default='src/planning-life-data.js')
args = parser.parse_args()
archive = Path(args.archive)
period = '2022/2024'
selected = {}
expectancy = {}
vectors = {}
with zipfile.ZipFile(archive) as source:
    metadata = source.read('13100114_MetaData.csv').decode('utf-8-sig')
    if '2022/2024 are considered' not in metadata or 'preliminary' not in metadata:
        raise ValueError('Recheck the preliminary-period metadata before updating this snapshot')
    with source.open('13100114.csv') as raw:
        for row in csv.DictReader(io.TextIOWrapper(raw, encoding='utf-8-sig')):
            if row['GEO'] != 'Canada' or row['REF_DATE'] != period or row['Sex'] not in ('Males', 'Females'):
                continue
            age = int(row['Age group'].split()[0])
            is_lx = row['Element'] == 'Number of survivors at age x (lx)' and 65 <= age <= 100
            is_ex = row['Element'] == 'Life expectancy (in years) at age x (ex)' and age == 65
            if not (is_lx or is_ex):
                continue
            if row['UOM'] != 'Number' or row['SCALAR_FACTOR'] != 'units' or row['STATUS'] not in ('', 'p') or not row['VALUE']:
                raise ValueError('Unexpected unit, scale or suppressed value')
            key = (age, row['Sex'])
            target = selected if is_lx else expectancy
            if key in target:
                raise ValueError('Duplicate observation')
            target[key] = float(row['VALUE'])
            vectors[f'{age}:{row["Sex"]}:{"lx" if is_lx else "ex"}'] = row['VECTOR']
if len(selected) != 72 or len(expectancy) != 2:
    raise ValueError('Incomplete selected series')
for sex in ('Males', 'Females'):
    values = [selected[age, sex] for age in range(65, 101)]
    if not all(a >= b >= 0 for a, b in zip(values, values[1:])) or values[0] <= 0:
        raise ValueError('Invalid life-table survivor counts')
snapshot = {
    'publisher': 'Statistics Canada', 'table': '13-10-0114-01', 'period': period,
    'geography': 'Canada', 'released': '2026-01-13', 'retrieved': '2026-10-25',
    'preliminary': True,
    'url': 'https://www150.statcan.gc.ca/t1/tbl1/en/tv.action?pid=1310011401',
    'download': 'https://www150.statcan.gc.ca/n1/tbl/csv/13100114-eng.zip',
    'archiveSHA256': hashlib.sha256(archive.read_bytes()).hexdigest(),
    'method': 'Conditional survival to age x from 65 = lx / l65, within each source sex category. Period life table; no future mortality improvements are projected.',
    'notes': '2022/2024 is preliminary under source metadata note 14, even though individual CSV STATUS cells are blank. lx counts describe a synthetic initial cohort of 100,000, not a survey sample.',
    'columns': ['age', 'Males lx', 'Females lx'],
    'rows': [[age, int(selected[age, 'Males']), int(selected[age, 'Females'])] for age in range(65, 101)],
    'remainingYearsAt65': {sex: expectancy[65, sex] for sex in ('Males', 'Females')},
    'vectors': vectors
}
Path(args.output).write_text('// Public Statistics Canada observations. Generated by scripts/extract-planning-life-table.py.\nexport const lifeSource = ' + json.dumps(snapshot, ensure_ascii=False, indent=2) + ';\n')
print(f'Extracted 72 survivor counts and 2 life-expectancy observations for {period}.')
