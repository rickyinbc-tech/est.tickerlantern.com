import json
import atexit
import os
import subprocess
import sys

SESSION = f'est-growth-sync-qa-{os.getpid()}'
atexit.register(lambda: subprocess.run(['agent-browser', '--session', SESSION, 'close'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False))
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8764/'
def browser(*args):
    return subprocess.check_output(['agent-browser', '--session', SESSION, *args], text=True).strip()
def value(script):
    return json.loads(browser('eval', script))
def fill(selector, text):
    browser('fill', selector, str(text))
def index(index_id):
    browser('click', '#index-list button[data-index="' + index_id + '"]')
def state():
    return value('({index:document.querySelector("#scenario-index-label").textContent,mode:document.querySelector("#growthMode").value,growth:Number(document.querySelector("#growth").value),years:Number(document.querySelector("#years").value),rates:Array.from(document.querySelectorAll("[data-growth-year]"),el=>Number(el.value)),irr:document.querySelector("#cash-irr").textContent})')
def check(label, passed):
    print(('PASS' if passed else 'FAIL') + ': ' + label, flush=True)
    if not passed:
        print(state(), flush=True)
        raise SystemExit(1)

browser('open', URL)
browser('wait', '#index-list button[data-index="nasdaq100"]:enabled')
browser('eval', 'document.documentElement.style.scrollBehavior="auto"')
browser('eval', 'localStorage.removeItem("tickerlantern.est.scenarios.v1")')
browser('open', URL)
browser('wait', '#index-list button[data-index="nasdaq100"]:enabled')
browser('eval', 'document.documentElement.style.scrollBehavior="auto"')
index('sp500')
browser('click', '#reset-model')
browser('select', '#growthMode', 'constant')
fill('#growth', 9)
index('nasdaq100')
checks = {
    'growth stays independent between indices': value('Number(document.querySelector("#growth").value)') == 6,
    'annual growth editor exists': value('Boolean(document.querySelector("#growthMode"))'),
}
for label, passed in checks.items():
    print(('PASS' if passed else 'FAIL') + ': ' + label, flush=True)
if not all(checks.values()):
    raise SystemExit(1)

index('sp500')
browser('select', '#growthMode', 'annual')
check('choosing yearly mode immediately reveals every annual field', value('!document.querySelector("#annual-growth-panel").hidden && document.querySelectorAll("[data-growth-year]").length === Number(document.querySelector("#years").value)'))
fill('#years', 3)
for year, rate in enumerate([10, -5, 20], 1):
    fill('#growth-year-' + str(year), rate)
fill('#entryPE', 20)
fill('#exitPE', 20)
check('three independent rates render for the selected horizon', state()['rates'] == [10, -5, 20])
last = value('Array.from(document.querySelector("#annual-data-body").lastElementChild.children,el=>el.textContent)')
check('annual table compounds EPS and price using the yearly schedule', last[2] == '6.27' and last[4] == '125.40')
check('charts and scenario context use the yearly schedule', value('document.querySelector("#index-model-note").textContent.includes("[10%, -5%, 20%]") && document.querySelector("#wealth-chart").textContent.includes("125.4")'))

# Capture the CSV generated by the real Download button without writing a download.
browser('eval', 'window.qaCreateURL=URL.createObjectURL; URL.createObjectURL=blob=>{window.qaCSV=blob; return window.qaCreateURL(blob)}; window.qaAnchorClick=HTMLAnchorElement.prototype.click; HTMLAnchorElement.prototype.click=function(){if(!this.download)window.qaAnchorClick.call(this)}')
browser('eval', 'document.querySelector("#download-csv").click()')
csv = value('window.qaCSV.text()')
check('download uses the same yearly rates and final price', [float(line.split(',')[-1]) for line in csv.splitlines()[2:]] == [10,-5,20] and abs(float(csv.splitlines()[-1].split(',')[3])-125.4)<1e-8)

index('nasdaq100')
browser('select', '#growthMode', 'annual')
fill('#years', 2)
fill('#growth-year-1', -3)
fill('#growth-year-2', 4)
index('sp500')
check('switching indices restores the first schedule and holding period', state()['rates'] == [10,-5,20] and state()['years'] == 3)
before = state()['irr']
browser('open', URL)
browser('wait', '#index-list button[data-index="nasdaq100"]:enabled')
browser('eval', 'document.documentElement.style.scrollBehavior="auto"')
check('reload restores the saved yearly path and matching return', state()['rates'] == [10,-5,20] and state()['irr'] == before)
index('nasdaq100')
check('reload also retains the other benchmark independently', state()['rates'] == [-3,4] and state()['years'] == 2)
index('sp500')
fill('#years', 2)
fill('#years', 3)
check('shortening and extending the horizon preserves later rates', state()['rates'] == [10,-5,20])
fill('#years', 4)
check('an added year uses only this benchmark’s default rate', state()['rates'] == [10,-5,20,9])
fill('#years', 3)
fill('#growth-year-2', '')
check('a blank yearly rate blocks stale results and exports', value('document.querySelector("#valid-output").hidden && document.querySelector("#download-csv").disabled && document.querySelector("#growth-year-2").getAttribute("aria-invalid")==="true"'))
fill('#growth-year-2', -5)
browser('click', '#check-data')
browser('wait', '#check-data:enabled')
check('source refresh preserves the complete yearly path', state()['rates'] == [10,-5,20])
browser('click', '#restore-source')
check('restoring sourced valuations keeps the custom yearly schedule', state()['rates'] == [10,-5,20] and state()['mode'] == 'annual')
browser('click', '[data-preset="compression"]')
check('presets preserve the yearly path', state()['rates'] == [10,-5,20] and state()['mode'] == 'annual')
browser('click', '#sensitivity-body button')
check('sensitivity selection explicitly switches to a constant-rate path', state()['mode'] == 'constant')
browser('select', '#growthMode', 'annual')
check('the yearly path can be recovered after selecting sensitivity', state()['rates'] == [10,-5,20])
browser('click', '#reset-model')
check('reset affects only the selected index', state()['mode'] == 'source' and state()['years'] == 1 and state()['rates'] == [16])
index('nasdaq100')
check('resetting one benchmark leaves the other yearly path saved', state()['rates'] == [-3,4] and state()['years'] == 2)
print('All growth synchronization browser checks passed.', flush=True)
