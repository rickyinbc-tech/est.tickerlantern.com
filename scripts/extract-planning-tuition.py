"""Extract a small attributed public tuition snapshot; keep raw downloads in qa/."""
import argparse,csv,hashlib,io,json,zipfile
from pathlib import Path

p=argparse.ArgumentParser();p.add_argument('--archive',required=True);p.add_argument('--output',default='src/planning-tuition-data.js');args=p.parse_args()
archive=Path(args.archive);period='2026/2027'
provinces=['Newfoundland and Labrador','Prince Edward Island','Nova Scotia','New Brunswick','Quebec','Ontario','Manitoba','Saskatchewan','Alberta','British Columbia']
levels=['Canadian undergraduate','International undergraduate'];selected={}
with zipfile.ZipFile(archive) as z:
    metadata=z.read('37100045_MetaData.csv').decode('utf-8-sig')
    assert 'Data for 2026/2027 are preliminary.' in metadata,'Recheck source-vintage status'
    assert '2023/2024 Postsecondary Student Information System' in metadata,'Recheck enrolment weighting vintage'
    with z.open('37100045.csv') as f:
        for r in csv.DictReader(io.TextIOWrapper(f,encoding='utf-8-sig')):
            if r['REF_DATE']!=period:continue
            if not (r['GEO']=='Canada' and r['Level of study'] in levels or r['GEO'] in provinces and r['Level of study']=='Canadian undergraduate'):continue
            assert r['UOM']=='Current dollars' and r['SCALAR_FACTOR']=='units'
            assert r['STATUS'] in ('','p') and not r['SYMBOL'] and r['VALUE'],'Unexpected missing/suppressed value'
            key=(r['GEO'],r['Level of study']);assert key not in selected,'Duplicate series'
            value=float(r['VALUE']);assert value>0 and value.is_integer()
            selected[key]={'value':int(value),'vector':r['VECTOR']}
assert len(selected)==12,'Incomplete selected coverage'
snapshot={
    'publisher':'Statistics Canada','table':'37-10-0045-01','period':period,'released':'2026-09-16','retrieved':'2026-10-25','preliminary':True,
    'url':'https://www150.statcan.gc.ca/t1/tbl1/en/tv.action?pid=3710004501','download':'https://www150.statcan.gc.ca/n1/tbl/csv/37100045-eng.zip',
    'archiveSHA256':hashlib.sha256(archive.read_bytes()).hexdigest(),'weights':'2023/2024 Postsecondary Student Information System enrolment',
    'scope':'Weighted annual undergraduate tuition, current CAD, public degree-granting institutions. Compulsory fees, living costs and student aid are separate. Ten provincial observations; no territory is shown.',
    'national':[{'label':level,**selected['Canada',level]} for level in levels],
    'provinces':[{'label':geo,**selected[geo,'Canadian undergraduate']} for geo in provinces]
}
Path(args.output).write_text('// Public Statistics Canada data; generated by scripts/extract-planning-tuition.py.\nexport const tuitionSource = '+json.dumps(snapshot,ensure_ascii=False,indent=2)+';\n')
print(json.dumps({'observations':len(selected),'national':snapshot['national'],'provinces':snapshot['provinces'],'preliminary':True,'sha256':snapshot['archiveSHA256']},indent=2))
