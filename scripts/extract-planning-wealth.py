#!/usr/bin/env python3
"""Reproduce a narrow public 2023 SFS snapshot from the original HTML table."""
import argparse
import hashlib
import json
from html.parser import HTMLParser
from pathlib import Path

class TableRows(HTMLParser):
    def __init__(self):
        super().__init__(); self.rows=[]; self.row=None; self.cell=None
    def handle_starttag(self, tag, attrs):
        if tag=='tr': self.row=[]
        if tag in ('th','td') and self.row is not None: self.cell={'text':'','attrs':dict(attrs)}
    def handle_data(self, text):
        if self.cell is not None: self.cell['text']+=text
    def handle_endtag(self, tag):
        if tag in ('th','td') and self.cell is not None:
            self.cell['text']=' '.join(self.cell['text'].split()); self.row.append(self.cell); self.cell=None
        if tag=='tr' and self.row is not None: self.rows.append(self.row); self.row=None

def extract(path):
    raw=path.read_bytes(); html=raw.decode('utf-8'); parser=TableRows(); parser.feed(html)
    assert 'All dollar amounts are in constant 2023 dollars.' in html
    assert '2019 - Median net worth' in html and '2023 - Median net worth' in html
    names=['under 35','35 to 44','45 to 54','55 to 64','65 and older','Economic families','Persons not in an economic family']
    selected=[]
    for name in names:
        matches=[r for r in parser.rows if len(r)==11 and r[0]['text']==name]
        assert len(matches)==1, (name,'missing or duplicate row')
        row=matches[0]
        for index,header in [(9,'hdt001r1c10'),(10,'hdt001r1c11')]:
            assert header in row[index]['attrs'].get('headers','')
            assert 'uomt001r2c7' in row[index]['attrs'].get('headers','')
        values=[int(row[i]['text'].replace(',','')) for i in (9,10)]
        assert all(v>=0 for v in values)
        selected.append({'label':name,'before':values[0],'after':values[1]})
    return {'publisher':'Statistics Canada','survey':'Survey of Financial Security, 2023','released':'2024-10-29','retrieved':'2026-10-25','periods':[2019,2023],'unit':'Constant 2023 CAD','url':'https://www150.statcan.gc.ca/n1/daily-quotidien/241029/t001a-eng.htm','releaseUrl':'https://www150.statcan.gc.ca/n1/daily-quotidien/241029/dq241029a-eng.htm','sha256':hashlib.sha256(raw).hexdigest(),'ageRows':selected[:5],'familyRows':selected[5:]}

if __name__=='__main__':
    p=argparse.ArgumentParser(); p.add_argument('table',type=Path); p.add_argument('--check',action='store_true'); args=p.parse_args()
    output='// Public Statistics Canada observations; generated by scripts/extract-planning-wealth.py.\nexport const wealthSource = '+json.dumps(extract(args.table),indent=2,ensure_ascii=False)+';\n'
    dest=Path('src/planning-wealth-data.js')
    if args.check:
        assert dest.read_text()==output,'Source snapshot differs from validated extract'
        print('Verified 14 median observations, row labels, years, units and original HTML SHA-256.')
    else:
        dest.write_text(output); print('Wrote '+str(dest))
